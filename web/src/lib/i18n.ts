const tables: Record<Lang, Record<Key, string>> = { en, tr };
let current: Lang = 'en';
export function setLang(l: Lang) { current = l; }
export function getLang(): Lang { return current; }

export function t(key: Key, params?: Record<string, string | number>, lang: Lang = current): string {
  let s = tables[lang][key] ?? en[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

